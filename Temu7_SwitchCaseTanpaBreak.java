public class Temu7_SwitchCaseTanpaBreak {
    public static void main(String[] args) {
        int angka = 2;
        switch (angka) {
            case 1:
                System.out.println("Satu");
            case 2:
                System.out.println("Dua");
            case 3:
                System.out.println("Tiga");
            default:
                System.out.println("Bukan 1-3");
        }
    }
}
